const load = async (table, rows) => {
  if (!rows.length) return;
  const cols = Object.keys(rows[0]);
  for (const r of rows) {
    const vals = cols.map(c => (r[c] !== null && typeof r[c] === 'object') ? JSON.stringify(r[c]) : r[c]);
    await db.query(`insert into ${table} (${cols.map(c => `"${c}"`).join(',')}) overriding system value values (${cols.map((_, i) => `$${i + 1}`).join(',')})`, vals);
  }
};
